#!/bin/bash
# Regenerate Models/Generated/*.swift from the db3 type file
# `Sources/<App>/bao-codegen.json` names.
#
# `scripts/codegen.sh` runs this on every build path: `./build.sh`, `./run.sh`,
# `./run-ios.sh`, `./test.sh`, and the Xcode target's pre-build phase. A bare
# `swift build` runs no codegen and compiles the committed emission.
#
# `bao-codegen.json` sits at the root of the app's sources, and takes every
# form the swift-client codegen plugin takes:
#
#   { "input": "../../primitive/dev/db3-types/notes.toml" }   one db3 type
#                                                            file, relative to
#                                                            that directory (or
#                                                            absolute)
#   { "inputs": ["../../primitive/dev/db3-types"] }           several: type
#                                                            files, or
#                                                            directories of them
#   { "input": null }                                        no data model yet
#
# With `inputs`, one run generates every named type into `Models/Generated/`
# with one `GeneratedModels` barrel. A directory contributes every `*.toml`
# directly inside it, in name order, and a file named twice counts once; a
# directory holding no type file yet is handed to the tool as it is, which
# writes the empty barrel.
#
# With no schema (`null`, an empty object, or no file at all) the tool runs
# over an empty TOML, so the committed empty `GeneratedModels` barrel is
# regenerated byte for byte. Anything else — another key, both `input` and
# `inputs`, a non-string or empty path, a path that does not exist — fails
# naming the file. It never falls back silently to generating nothing.
#
# Usage:
#   bash scripts/generate-models.sh [--verify-project]
#
# --print-schema resolves the schema and the app's source directory and
# generates nothing. It prints the first input (empty when there is no schema),
# then the app's source directory, then every further input, one per line:
# each type file, and each directory `inputs` names. `scripts/codegen.sh` uses
# it to name the inputs in the build phase's declared input list rather than
# repeating the resolution.
#
# --verify-project additionally fails when the Xcode source list and the
# emitted files disagree, in either direction. Codegen can refresh a CHANGED
# model in place, but ADDING one emits a file the `.pbxproj` does not compile,
# and REMOVING one sweeps a file the `.pbxproj` still compiles; only `xcodegen
# generate` moves that list. Inside a build phase there is no regenerating the
# project we are already building, so the build stops with the fix rather than
# compiling an app quietly missing the type. Call sites that regenerate the
# project right after (`run-ios.sh`) leave the flag off.
#
# The app root is resolved from this script's own path, not the caller's
# working directory: Xcode runs build phases from wherever it likes.
#
# Progress goes to stderr, so a caller capturing stdout gets nothing from here.
set -euo pipefail

cd "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# Xcode exports the target's SDK into every script phase. Everything this
# script runs is a host tool — `python3` reading the config, and `swift run`
# building the codegen tool — so inheriting the iOS simulator SDK makes them
# fail (or, worse, build something that cannot run here).
unset SDKROOT PLATFORM_NAME MACOSX_DEPLOYMENT_TARGET IPHONEOS_DEPLOYMENT_TARGET

VERIFY_PROJECT=false
PRINT_SCHEMA=false
while [ $# -gt 0 ]; do
    case "$1" in
        --verify-project) VERIFY_PROJECT=true; shift ;;
        --print-schema) PRINT_SCHEMA=true; shift ;;
        *) echo "Unknown argument: $1" >&2; exit 1 ;;
    esac
done

# The app's source directory: the one holding `bao-codegen.json`, else the one
# holding `Models/Generated/`, else the only one under `Sources/` — so a renamed
# app (`primitive init` scaffolds under your own name) needs no edit here.
APP_SOURCES=""
CONFIG=""
for candidate in Sources/*/bao-codegen.json; do
    [ -f "$candidate" ] || continue
    CONFIG="$candidate"
    APP_SOURCES="$(dirname "$candidate")"
    break
done
if [ -z "$APP_SOURCES" ]; then
    for candidate in Sources/*/Models/Generated; do
        [ -d "$candidate" ] || continue
        APP_SOURCES="$(dirname "$(dirname "$candidate")")"
        break
    done
fi
if [ -z "$APP_SOURCES" ]; then
    set -- Sources/*/
    if [ $# -eq 1 ] && [ -d "$1" ]; then
        APP_SOURCES="${1%/}"
    fi
fi
if [ -z "$APP_SOURCES" ]; then
    echo "error: no Sources/<App>/bao-codegen.json or Sources/<App>/Models/Generated/ — codegen cannot tell which target is the app." >&2
    exit 1
fi

# The configured inputs, or none. python3 rather than a sed match: the file
# is JSON, and a shape this script does not understand has to fail. It prints
# one `file<TAB>path` or `dir<TAB>path` line per input, in order — a named
# directory, then its type files — with paths spelled from the app root.
#
# The rules are the plugin's (`JsBaoCodegenInputs` in swift-client's
# `JsBaoCodegenPlugin.swift`); a template test compiles the plugin's resolver
# and fails when the two disagree. On top of them, `null` and `{}` mean no
# schema yet, which is why a key neither form defines fails here.
SCHEMA_FILES=()
SCHEMA_DIRS=()
SCHEMA_READS=()
if [ -n "$CONFIG" ]; then
    RESOLVED="$(python3 - "$CONFIG" "$APP_SOURCES" <<'PY'
import json, os, sys
path, base = sys.argv[1], sys.argv[2]
shape = ('expected {"input": "<db3 type file>"}, {"input": null} or '
         '{"inputs": ["<type file or directory>", ...]}')
try:
    with open(path) as f:
        data = json.load(f)
except ValueError as e:
    sys.exit(f"error: {path} is not valid JSON ({e}); {shape}.")
if not isinstance(data, dict):
    sys.exit(f"error: {path} must be a JSON object; {shape}.")
extra = sorted(k for k in data if k not in ("input", "inputs"))
if extra:
    sys.exit(f"error: {path} has {', '.join(repr(k) for k in extra)}; {shape}.")
if "input" in data and "inputs" in data:
    sys.exit(f"error: {path} names both \"input\" and \"inputs\"; keep one. {shape}.")

def spelled(entry):
    return entry if entry.startswith("/") else os.path.join(base, entry)

seen = set()
def emit(kind, p):
    if kind == "file":
        key = os.path.normpath(os.path.abspath(p))
        if key in seen:
            return
        seen.add(key)
    print(f"{kind}\t{p}")

if "inputs" in data:
    entries = data["inputs"]
    if not isinstance(entries, list) or not entries or not all(isinstance(e, str) for e in entries):
        sys.exit(f"error: {path} has an \"inputs\" that is not a non-empty list of paths; {shape}.")
    for entry in entries:
        entry = entry.strip()
        if not entry:
            sys.exit(f"error: {path} has an empty entry in \"inputs\"; {shape}.")
        p = spelled(entry)
        if os.path.isdir(p):
            emit("dir", p)
            for name in sorted(os.listdir(p)):
                member = os.path.join(p.rstrip("/") or "/", name)
                if name.endswith(".toml") and os.path.isfile(member):
                    emit("file", member)
        elif os.path.exists(p):
            emit("file", p)
        else:
            sys.exit(f"error: {path} names {entry}, which does not exist.")
else:
    value = data.get("input")
    if value is None:
        pass
    elif not isinstance(value, str) or not value.strip():
        sys.exit(f"error: {path} has an \"input\" that is not a path; {shape}.")
    else:
        entry = value.strip()
        p = spelled(entry)
        if not os.path.exists(p):
            sys.exit(f"error: {path} names {entry}, which does not exist.")
        if os.path.isdir(p):
            sys.exit(f"error: {path} names {entry}, which is a directory; "
                     "name a db3 type file, or list the directory in \"inputs\".")
        emit("file", p)
PY
)"
    while IFS="$(printf '\t')" read -r kind path; do
        case "$kind" in
            file) SCHEMA_FILES+=("$path") ;;
            dir)  SCHEMA_DIRS+=("$path") ;;
            *)    continue ;;
        esac
        SCHEMA_READS+=("$path")
    done <<EOF
$RESOLVED
EOF
fi
# Always the app's own directory: the generated types belong to this target
# even when the type file they come from lives outside it.
GEN_DIR="$APP_SOURCES/Models/Generated"

if [ "$PRINT_SCHEMA" = true ]; then
    if [ ${#SCHEMA_READS[@]} -eq 0 ]; then
        echo ""
        echo "$APP_SOURCES"
    else
        printf '%s\n' "${SCHEMA_READS[0]}" "$APP_SOURCES"
        [ ${#SCHEMA_READS[@]} -gt 1 ] && printf '%s\n' "${SCHEMA_READS[@]:1}"
    fi
    exit 0
fi

mkdir -p "$GEN_DIR"

# What the tool reads, as the plugin hands it over: every type file; else the
# named directories, so an empty `db3-types/` still gets its (empty) barrel;
# else — no schema — an empty TOML, under a fixed name, so the barrel's
# `Source:` line, and so the whole emission, is the same on every run.
TOOL_ARGS=()
EMPTY_DIR=""
if [ ${#SCHEMA_FILES[@]} -gt 0 ]; then
    for input in "${SCHEMA_FILES[@]}"; do TOOL_ARGS+=(--input "$input"); done
elif [ ${#SCHEMA_DIRS[@]} -gt 0 ]; then
    for input in "${SCHEMA_DIRS[@]}"; do TOOL_ARGS+=(--input "$input"); done
else
    EMPTY_DIR="$(mktemp -d)"
    trap 'rm -rf "$EMPTY_DIR"' EXIT
    : > "$EMPTY_DIR/empty-schema.toml"
    TOOL_ARGS+=(--input "$EMPTY_DIR/empty-schema.toml")
fi

echo "Running swift-bao-codegen..." >&2
swift run --package-path . swift-bao-codegen \
    "${TOOL_ARGS[@]}" \
    --output "$GEN_DIR" >&2

if [ "$VERIFY_PROJECT" = true ]; then
    # The check itself lives in its own script: `scripts/codegen.sh` runs it
    # across every generated directory at once, after every generator has
    # emitted. This flag keeps working for a caller that wants the model half
    # alone.
    # One input names the schema; several are named by the config that lists
    # them.
    LABEL="${CONFIG:-bao-codegen.json}"
    [ ${#SCHEMA_READS[@]} -eq 1 ] && LABEL="${SCHEMA_READS[0]}"
    bash scripts/verify-generated-project.sh --label "$LABEL" "$GEN_DIR"
fi

# A stamp for a phase that runs this script alone. Written last, so a failed
# codegen never marks the phase up to date.
if [ -n "${DERIVED_FILE_DIR:-}" ]; then
    mkdir -p "$DERIVED_FILE_DIR"
    touch "$DERIVED_FILE_DIR/models-codegen.stamp"
fi
